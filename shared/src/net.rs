#[derive(Component, Serialize, Deserialize, Clone, Copy, PartialEq, Debug, Default)]
pub struct InLargestAssembly;

/// Replicated launch state for a room, authored by the server onto that room's
/// state entity (the same room-scoped entity that carries the room's [`NetRoomFrame`])
/// so every client in the room sees the same countdown. A player
/// touching the room's largest assembly can start a launch ([`RequestLaunch`]); the
/// server runs the countdown here and, at blastoff, cuts the assembly's ground joints
/// and fires its rockets. Clients read this to draw the `3 → 2 → 1 → Blastoff!` banner
/// and — once `launched` — to apply the same balanced thrust to their *predicted*
/// rockets (so the liftoff is smooth, not rollback-jittered).
#[derive(Component, Serialize, Deserialize, Clone, Copy, PartialEq, Debug, Default)]
pub struct NetLaunch {
    /// Seconds left in the countdown while counting down (`> 0`); `0` when idle or
    /// already launched. Derived from [`blastoff_tick`](Self::blastoff_tick) — a HUD
    /// readout only. Never gate physics on it.
    pub remaining: f32,
    /// Whether blastoff has happened and the rockets are firing. A *level*: it arrives
    /// ~1 RTT after the fact, so it is right for visuals (banner, camera, planet ring)
    /// and wrong for physics — see [`launched_at`](Self::launched_at).
    pub launched: bool,
    /// The tick blastoff fires on, scheduled when the countdown arms and replicated
    /// [`LAUNCH_COUNTDOWN_TICKS`] (188) ahead of it. This is what makes liftoff
    /// tick-exact on every peer:
    /// the countdown gives everyone the answer long before the moment, so the client
    /// starts its burn (and cuts its predicted ground joints) on the *same* tick as
    /// the server instead of reacting to `launched` arriving late. `None` for a room
    /// that has never launched this session, and for a world restored from a save
    /// already in flight (nothing to schedule — `launched` covers it).
    pub blastoff_tick: Option<u32>,
    /// Everything the server's guidance optimizer sampled this launch's ascent program
    /// from, so the predicted client rebuilds the *identical* program rather than
    /// re-planning from its own live state a few ticks later. Replicating only the
    /// chosen angle was not enough — see [`LaunchSeed`](crate::guidance::LaunchSeed) for
    /// the 1.2 mrad standing command error that left behind.
    pub plan: crate::guidance::LaunchSeed,
}

/// How many ticks the pre-blastoff countdown runs for. Rounded **up** so the scheduled
/// moment is never earlier than [`LAUNCH_COUNTDOWN_SECS`](crate::launch::LAUNCH_COUNTDOWN_SECS)
/// — a countdown that fires a hair late is invisible; one that fires early clips the
/// banner. (`TICK` is 16 ms, not exactly 1/60 s, so this is 188, not 180.)
pub const LAUNCH_COUNTDOWN_TICKS: i32 = {
    let tick_ms = TICK.as_millis() as i32;
    let countdown_ms = (crate::launch::LAUNCH_COUNTDOWN_SECS * 1000.0) as i32;
    (countdown_ms + tick_ms - 1) / tick_ms
};

impl NetLaunch {
    /// Whether the engines are firing **at `tick`** — the predicate every physics site
    /// must use, on the server and on each predicted client alike.
    ///
    /// The point is that this is a pure function of a tick and a value replicated
    /// [`LAUNCH_COUNTDOWN_TICKS`] in advance, so both peers answer identically without
    /// either waiting to be told.
    ///
    /// Reading the `launched` *level* instead is what made the client start its burn
    /// **late on every single flight**: the level is replicate-only (no `.predict()`), so
    /// nothing ever replayed the missed ticks. How late depends on the link — measured at
    /// 4 ticks on the campaign's setup (a fixed 0.1997 m/s velocity deficit, exactly 4 ×
    /// the 0.04995 m/s a tick of thrust adds, which is how the lag was first identified)
    /// and at 1–2 ticks over loopback, where it was still late every run and still
    /// varied. Rollback absorbed the transient over ~100 ticks; it should never have
    /// existed. Note the deficit is not the whole cost — the client also held its
    /// predicted ground clamps for those ticks (see `release_predicted_ground_joints`).
    ///
    /// The tick delta is a wrapping `i32` (lightyear's `Tick` is a wrapping `u32`), so
    /// this stays correct across the counter's wrap and while a rollback replays ticks
    /// older than the schedule.
    pub fn launched_at(&self, tick: Tick) -> bool {
        match self.blastoff_tick {
            Some(scheduled) => {
                let elapsed: i32 = tick - Tick(scheduled);
                elapsed >= 0
            }
            // No schedule: a world restored from a save that was already in flight (or a
            // peer that connected mid-flight). The replicated level is all there is, and
            // it is correct — the launch is long past, so there is no tick to be exact about.
            None => self.launched,
        }
    }
}

/// Replicated **floating-origin frame** of a room, authored by the server onto the
/// room's state entity (alongside [`NetLaunch`]). Rooms whose
/// assembly climbs far from the origin are periodically **rebased**: the server
/// subtracts the assembly's position AND mean velocity from every room entity (a
/// Galilean boost into a co-moving frame — physics is invariant under it), so the
/// solver and the renderer always work near the origin at small local velocities
/// instead of starving f32 precision at extreme altitude (the old hard ceilings:
/// ~33 km ridden / ~524 km unmanned). The accumulated frame is the bookkeeping:
///
/// - true position = `offset` + local position (offset integrates as
///   `offset += velocity * dt` each fixed tick — f64, exact for any flight);
/// - true velocity = `velocity` + local velocity.
///
/// Client duties on a frame change: move the local ground to `-offset` (the true
/// ground position in room-local coordinates — fixes rendering, predicted physics,
/// and the flame ground raycast in one move) and derive HUD altitude/speed from the
/// frame. The rebase itself is PREDICTED: the decision is a pure function of sim
/// state ([`rebase_room_frame`]) that the client evaluates on its predicted world at
/// the same tick as the server (`predict_room_rebase`), so the shifted confirmed
/// state matches the shifted predicted state and no rollback fires. A mispredicted
/// rebase tick (the anchor crossing the trigger within the sims' sub-mm disagreement
/// of a tick boundary) degrades to the old behaviour: one uniform rollback whose
/// correction slides the whole scene rigidly.
#[derive(Component, Serialize, Deserialize, Clone, Copy, PartialEq, Debug, Default)]
pub struct NetRoomFrame {
    /// Room-frame origin in true world coordinates (f64: it grows without bound).
    pub offset: [f64; 3],
    /// Room-frame velocity in true world coordinates (the co-moving boost).
    pub velocity: [f32; 3],
    /// The server tick `offset` was sampled at. The frame is a linear recurrence
    /// (`offset += velocity·TICK` every tick, exactly, in f64), so this is what lets a
    /// predicted client reconstruct the frame at *its* tick instead of consuming the
    /// replicated sample as-is — see [`Self::frame_at`].
    pub tick: u32,
}

impl NetRoomFrame {
    /// The frame `(offset, velocity)` advanced to `tick` — the server's recurrence
    /// (`offset += velocity·TICK` per tick) replayed from the replicated sample, exact
    /// in f64 because that is exactly how the server integrates it.
    ///
    /// Predicted physics MUST use this, not the raw replicated value and not the
    /// client's visual frame mirror: the raw sample is ~1 packet stale (at 200 m/s
    /// that is metres of `r` error in `gravity_at`/`drag_force` — a standing
    /// differential acceleration against the server measured at ~0.003 m/s², enough
    /// to saw through the position tolerance every ~8 s), and the visual mirror is
    /// render-frame state, so a rollback replay would read ONE value across every
    /// replayed tick while the server's frame advanced per tick.
    pub fn frame_at(&self, tick: Tick) -> (bevy::math::DVec3, Vec3) {
        let velocity = Vec3::from_array(self.velocity);
        // Wrapping i32 tick delta: negative while a rollback replays ticks older than
        // the sample, which extrapolates backward along the same recurrence.
        let dticks: i32 = tick - Tick(self.tick);
        let offset = bevy::math::DVec3::from_array(self.offset)
            + velocity.as_dvec3() * (f64::from(dticks) * TICK.as_secs_f64());
        (offset, velocity)
    }

    /// Whether the room is currently rebased away from the true origin. An active
    /// frame means the true ground is far away: the server drops the ground bit from
    /// the room's collision filters and the client moves its ground to `-offset`.
    pub fn is_active(&self) -> bool {
        self.offset != [0.0; 3] || self.velocity != [0.0; 3]
    }
}

/// Local drift of a room's assembly that triggers a floating-origin rebase.
pub const REBASE_TRIGGER_M: f32 = 2000.0;

/// True distance from the origin below which an active frame resets to exactly
/// zero (real coordinates, real ground). Half of [`REBASE_TRIGGER_M`], so the two
/// can't flap: right after a reset the local drift is under the trigger.
pub const REBASE_RESET_M: f64 = 1000.0;

/// Where a rebase parks the assembly above the local origin. Keeps the freshly
/// shifted content clear of the phantom ground collider (and of the client's
/// not-yet-moved local ground while the client applies the shift).
pub const REBASE_REST_Y: f32 = 100.0;

/// A rebase decision applied to a room frame: subtract `(dpos, dvel)` from every
/// room entity's position/velocity, and the frame becomes `(offset, velocity)`.
pub struct RebaseOutcome {
    pub dpos: Vec3,
    pub dvel: Vec3,
    pub offset: bevy::math::DVec3,
    pub velocity: Vec3,
}

/// The floating-origin rebase decision for one room, as a pure function of the
/// frame and the room's anchor (its largest assembly's volume-weighted mean
/// position/velocity): `Some` when the room rebases this tick, with the shift to
/// subtract from every room entity and the resulting frame.
///
/// This is THE single decision path — the server applies it authoritatively
/// (`rebase_room_frames`) and a predicted client mirrors it on its predicted world
/// at the same tick (`predict_room_rebase`), so the rebase never reaches the
/// rollback comparator as a surprise. Any fork in this logic is a guaranteed
/// rollback per rebase, so keep it here, shared.
///
/// The reset branch lands the frame *exactly* on zero (assignment, not
/// accumulation of the inverse shift — an f32 round trip would leave a residue and
/// the ground must become real again).
pub fn rebase_room_frame(
    offset: bevy::math::DVec3,
    velocity: Vec3,
    anchor_pos: Vec3,
    anchor_vel: Vec3,
) -> Option<RebaseOutcome> {
    let active = offset != bevy::math::DVec3::ZERO || velocity != Vec3::ZERO;
    let true_anchor = offset + anchor_pos.as_dvec3();
    if active && true_anchor.length() < REBASE_RESET_M {
        Some(RebaseOutcome {
            dpos: -offset.as_vec3(),
            dvel: -velocity,
            offset: bevy::math::DVec3::ZERO,
            velocity: Vec3::ZERO,
        })
    } else if anchor_pos.length() > REBASE_TRIGGER_M {
        let dpos = anchor_pos - Vec3::Y * REBASE_REST_Y;
        Some(RebaseOutcome {
            dpos,
            dvel: anchor_vel,
            offset: offset + dpos.as_dvec3(),
            velocity: velocity + anchor_vel,
        })
    } else {
        None
    }
}

/// The weighted mean position/velocity of a set of `(position, velocity, weight)`
/// samples — the rebase anchor arithmetic, shared so the server's authoritative
/// anchor and the client's predicted one ([`rebase_room_frame`]'s input) are the
/// same reduction and can't fork. `None` when the samples carry no weight.
/// (Iteration *order* still differs between the peers — ECS query order vs the
/// server's index arrays — which is ULP-scale noise, dwarfed by the sims' sub-mm
/// state drift.)
pub fn weighted_anchor(
    samples: impl Iterator<Item = (Vec3, Vec3, f32)>,
) -> Option<(Vec3, Vec3)> {
    let (mut weighted_pos, mut weighted_vel, mut mass) = (Vec3::ZERO, Vec3::ZERO, 0.0f32);
    for (position, velocity, weight) in samples {
        weighted_pos += position * weight;
        weighted_vel += velocity * weight;
        mass += weight;
    }
    (mass > 0.0).then(|| (weighted_pos / mass, weighted_vel / mass))
}

/// A part's volume — the mass proxy under uniform density (full cuboid volume, or the
/// rocket's precomputed cylinder+cone volume). Shared by the server's assembly COM,
/// the launch COM, and the client's predicted rebase anchor so all weigh parts
/// identically.
pub fn part_volume(shape: PartShape) -> f32 {
    match shape {
        PartShape::Cuboid { half_extents } => {
            let he = Vec3::from_array(half_extents);
            8.0 * he.x * he.y * he.z
        }
        PartShape::RocketEngine => crate::part::ROCKET_VOLUME,
    }
}

/// Replicated hold state for a part a player is currently holding: who holds it
/// (their [`NetPlayer::client_id`]) and the hold point + target orientation the server
