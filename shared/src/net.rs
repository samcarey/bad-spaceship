/// The replicated shape of a part — enough for a client to rebuild the collider and
/// render mesh. A cuboid carries its own half-extents; a rocket engine is fixed
/// geometry (the `ROCKET_*` constants in `part.rs`), so it needs no parameters. This
/// is the shape discriminant `NetPart` carries so rockets replicate like any part
/// (before this, `NetPart` was cuboid-only and rockets were single-player).
#[derive(Serialize, Deserialize, Clone, Copy, PartialEq, Debug)]
pub enum PartShape {
    /// A random box; `half_extents` are half the full extents (`Collider::cuboid`
    /// takes full extents = 2 × these).
    Cuboid { half_extents: [f32; 3] },
    /// A rocket engine: cylinder body + cone flare, built from the shared `ROCKET_*`
    /// geometry constants (no per-instance parameters).
    RocketEngine,
}

impl Default for PartShape {
    // A degenerate unit cuboid — only hit if a `NetPart` is ever default-constructed
    // before replication fills it; real parts always carry a concrete shape.
    fn default() -> Self {
        PartShape::Cuboid { half_extents: [0.5, 0.5, 0.5] }
    }
}

/// Replicated shape of a part (see [`PartShape`]) plus a stable cross-network id. The
/// shape lets a client rebuild the collider + render mesh; the part's live pose rides
/// on the predicted Avian `Position`/`Rotation`. `id` is the server part entity's bits
/// — a *stable* identity (replicated onto both the client's `Confirmed` and `Predicted`
/// copies) that lets the client match a replicated joint's endpoints (`NetJoint`) to the
/// local *predicted* part entities, without depending on lightyear's confirmed→predicted
/// entity mapping.
#[derive(Component, Serialize, Deserialize, Clone, Copy, PartialEq, Debug, Default)]
pub struct NetPart {
    pub shape: PartShape,
    pub id: u64,
    /// Appearance seed (see `PartSeed`): clients derive the part's metal look
    /// from it, so every client renders the same part identically. (Ignored for
    /// rockets, whose striped body material is fixed.)
    pub seed: u32,
}

/// A replicated joint between two parts. Carries enough to reconstruct the joint
/// as *real predicted physics* on each client: the stable ids (`NetPart::id`) of
/// the two bodies and their body-local (COM-relative) anchors, in the same order
/// the server's `SphericalJoint` uses (`body1`/`anchor1` ↔ `local_anchor1`). The
/// client looks up the matching *predicted* part entities by id and spawns a real
/// Avian `SphericalJoint` between them, so the assembly is held together by the
/// client's own simulation (and survives rollback) — not just rendered. Without
/// this the predicted parts are unconstrained locally and a lifted assembly sags
/// apart, corrected only by replication.
#[derive(Component, Serialize, Deserialize, Clone, Copy, PartialEq, Debug, Default)]
pub struct NetJoint {
    pub body1: u64,
    pub body2: u64,
    pub anchor1: [f32; 3],
    pub anchor2: [f32; 3],
}

/// A replicated **player-lock weld**: a joint pinning a player's avatar to a part it
/// was touching when the player pressed "Lock" (one per weld contact). Carries enough
/// for each client to rebuild the constraint as *real predicted physics* — the exact
/// counterpart of [`NetJoint`], but the first body is an **avatar** (resolved by its
/// [`NetPlayer::client_id`], since avatars have no `NetPart::id`) and the second a part
/// (by [`NetPart::id`]). Anchors are body-local (origin-relative), frozen at the
/// contact so the weld has zero rest error. Clients also *derive* each player's locked
/// state from these (a player is locked iff any `NetLockJoint` names them), which is
/// what gates the launch button on "everyone is attached to the assembly".
#[derive(Component, Serialize, Deserialize, Clone, Copy, PartialEq, Debug, Default)]
pub struct NetLockJoint {
    /// The locked player's [`NetPlayer::client_id`].
    pub player: u64,
    /// The welded part's [`NetPart::id`].
    pub part: u64,
    /// Anchor in the avatar's local frame (identity rotation — the body is
    /// rotation-locked — so this is just `contact − avatar position` at weld time).
    pub anchor_player: [f32; 3],
    /// Anchor in the part's local frame.
    pub anchor_part: [f32; 3],
}

/// Sentinel [`NetJoint`] endpoint id meaning "the ground" (the `Grass` bowl). The
