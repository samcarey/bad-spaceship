/// Replicated cuboid shape of a part (full extents = 2 × `half_extents`), plus a
/// stable cross-network id. The shape lets a client rebuild the render mesh; the
/// part's live pose rides on the predicted Avian `Position`/`Rotation`. `id` is
/// the server part entity's bits — a *stable* identity (replicated onto both the
/// client's `Confirmed` and `Predicted` copies) that lets the client match a
/// replicated joint's endpoints (`NetJoint`) to the local *predicted* part
/// entities, without depending on lightyear's confirmed→predicted entity mapping.
#[derive(Component, Serialize, Deserialize, Clone, Copy, PartialEq, Debug, Default)]
pub struct NetPart {
    pub half_extents: [f32; 3],
    pub id: u64,
    /// Appearance seed (see `PartSeed`): clients derive the part's metal look
    /// from it, so every client renders the same part identically.
    pub seed: u32,
}

/// A replicated joint between two parts. Carries enough to reconstruct the joint
/// as *real predicted physics* on each client: the stable ids (`NetPart::id`) of
/// the two bodies and their body-local (COM-relative) anchors, in the same order
/// the server's `SphericalJoint` uses (`body1`/`anchor1` ↔ `local_anchor1`). The
/// client looks up the matching *predicted* part entities by id and spawns a real
/// Avian `SphericalJoint` between them, so the assembly is held together by the
/// client's own simulation (and survives rollback) — not just rendered. Without
/// this the predicted parts are unconstrained locally and a lifted assembly sags
/// apart, corrected only by replication.
#[derive(Component, Serialize, Deserialize, Clone, Copy, PartialEq, Debug, Default)]
pub struct NetJoint {
    pub body1: u64,
    pub body2: u64,
    pub anchor1: [f32; 3],
    pub anchor2: [f32; 3],
}

/// Sentinel [`NetJoint`] endpoint id meaning "the ground" (the `Grass` bowl). The
/// ground is spawned locally on every peer by `MapPlugin` rather than replicated,
/// so it has no `NetPart::id`; each client resolves this sentinel to its own local
/// ground entity. Never collides with a real id: part ids are live `Entity` bits,
/// and `u64::MAX` is not a valid entity encoding.
pub const GROUND_JOINT_ID: u64 = u64::MAX;

/// Replicated hold state for a part a player is currently holding: who holds it
/// (their [`NetPlayer::client_id`]) and the hold point + target orientation the server
/// is springing it toward (the holder's forwarded `hold_target`/`hold_rotation`). All
/// loose parts are predicted on *every* client (`PredictionTarget::All`), but only the
/// holder runs the hold spring locally — so without this a remote observer predicts the
/// held part in **free-fall** and replication yanks it back up every snapshot, making it
/// sag and bob for everyone except the holder. With it, each client springs the held
/// part toward this target with the same `apply_hold_spring` the server uses, so the
/// part floats smoothly for observers too. The holder ignores its own (it predicts with
/// its local, zero-delay hold point); the component is removed when the part is released.
#[derive(Component, Serialize, Deserialize, Clone, Copy, PartialEq, Debug, Default)]
pub struct NetHold {
    /// The holder's `NetPlayer::client_id`, so the holder's own client can skip it.
    pub holder: u64,
    /// Hold-point world position the part is sprung toward (the holder's `hold_target`).
    pub target: [f32; 3],
    /// Target orientation for the held part (the holder's `hold_rotation`).
    pub rotation: [f32; 4],
}

/// A player's display **name**, replicated to every client sharing the room so it
/// can be drawn as a billboard over the avatar's head and listed in the on-screen
/// roster. The server assigns a unique default (`"Player N"`, lowest free N within
/// the room) when the avatar joins its room (`assign_rooms`); the owning client can
/// rename it by sending a [`SetName`] message, which the server sanitises and writes
/// back here. Not `Copy` (owns a `String`), so — unlike the other replicated
/// components — it derives only `Clone`; replication clones it, which is all
/// `.replicate()` needs. No interpolation (a name is discrete, not eased).
#[derive(Component, Serialize, Deserialize, Clone, PartialEq, Debug, Default)]
pub struct NetName(pub String);

/// Client → server request to rename the sender's own avatar. The server resolves
/// the sender's avatar (via `ControlledBy`), [`sanitize_name`]s the string, and
/// writes it onto that avatar's [`NetName`] (from which it re-replicates to everyone
/// in the room). Sent on the reliable [`ControlChannel`] so a one-shot rename isn't
/// dropped.
#[derive(Serialize, Deserialize, Clone, PartialEq, Debug)]
pub struct SetName(pub String);

/// Client → server request to teleport the sender's avatar back to a fresh spawn
