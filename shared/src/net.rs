/// The simulation tick interval (60 Hz). The client and server must agree on
/// this, so it lives in the shared protocol — both pass it to their lightyear
/// plugin group's `tick_duration`.
pub const TICK: Duration = Duration::from_millis(1000 / 60);

/// Identifies which connected client controls a replicated player entity.
#[derive(Component, Serialize, Deserialize, Clone, Copy, PartialEq, Debug)]
pub struct NetPlayer {
    pub client_id: u64,
    /// Which of the client's monster models this player wears (assigned by the
    /// server from the persistent resume id via `monster_index`, so it
    /// survives reload/reset and every client renders the same one).
    pub monster: u8,
}

/// How many monster models the client ships (`client/src/monster.rs`, which
/// compile-time asserts its table length against this).
pub const MONSTER_COUNT: u8 = 8;

/// One splitmix64 step: advances `state` and returns a well-mixed u64. THE
/// deterministic random primitive for everything derived from replicated
/// seeds (monster assignment, part metal looks): hand-rolled because the
/// derivation must be identical across platforms and versions — every client
/// (wasm + native) must derive the same result from the same seed, and `rand`
/// guarantees neither cross-version nor cross-platform stability for its
/// small RNGs.
pub fn splitmix64(state: &mut u64) -> u64 {
    *state = state.wrapping_add(0x9E37_79B9_7F4A_7C15);
    let mut z = *state;
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

/// Deterministically assign a monster from a player's persistent id. Used by
/// the server (resume id from the connect token) AND the single-player client
/// (the same resume id read locally), so a given browser is the same monster
/// everywhere.
pub fn monster_index(id: u64) -> u8 {
    let mut state = id;
    (splitmix64(&mut state) % MONSTER_COUNT as u64) as u8
}

/// Pack a lobby code into the fixed 6-byte field the server keys rooms by
/// ([`NetInput::room`]): the matchmaker hands out 6 uppercase chars, so
/// uppercase, take up to 6 bytes, zero-pad. An empty code maps to all-zero —
/// the shared default room. Lives beside the wire format it defines so every
/// client of the protocol (the game client, the headless bot) packs rooms
/// identically.
pub fn room_code_bytes(code: &str) -> [u8; 6] {
    let mut out = [0u8; 6];
    for (slot, byte) in out.iter_mut().zip(code.to_ascii_uppercase().bytes()) {
        *slot = byte;
    }
    out
}

/// Pack a persistent resume id into a netcode connect-token `user_data` block
/// (little-endian u64 at offset 0), and read it back out. The one definition of
/// the wire layout shared by every writer (game client, headless bot) and the
/// server's connect-time reader — change it here or nowhere.
pub fn resume_user_data(resume_id: u64) -> [u8; 256] {
    let mut out = [0u8; 256];
    out[..8].copy_from_slice(&resume_id.to_le_bytes());
    out
}

/// See [`resume_user_data`].
pub fn resume_id_from_user_data(user_data: &[u8; 256]) -> u64 {
    u64::from_le_bytes(user_data[..8].try_into().unwrap())
}

/// Per-tick client → server **input intent** (not pose). The server runs the
/// authoritative character simulation from this intent (move direction, jump,
/// look angle), so the world is server-authoritative and — once client-side
/// prediction lands — the client predicts the same simulation locally and the
/// server reconciles only on divergence. The grab-ray fields are still sent from
/// the client's camera for now (the server's grab uses them directly); a later
/// phase reconstructs the ray from the simulated character + look angles.
///
/// Sent via lightyear's native-input channel (registered with
/// `InputPlugin::<NetInput>` in `ProtocolPlugin`); native inputs must be
/// `Serialize`/`Deserialize`/`Clone`/`PartialEq`/`Debug`/`Default` + `Reflect` +
/// `MapEntities`.
#[derive(Serialize, Deserialize, Clone, Copy, PartialEq, Debug, Default, Reflect)]
pub struct NetInput {
    /// Look-relative move intent: `[strafe(+right), forward]`, clamped to length 1
    /// (analog magnitude preserved for the touch joystick / gamepad).
    pub move_xz: [f32; 2],
    /// Jump intent this tick.
    pub jump: bool,
    /// Absolute look yaw (radians) — the movement basis and the avatar's facing.
    pub yaw: f32,
    /// Absolute look pitch (radians) — used by the server grab-ray reconstruction
    /// in a later phase (forwarded now to stabilise the protocol).
    pub pitch: f32,
    /// Camera-orbit-center world position — the origin of the grab look-ray.
    pub grab_origin: [f32; 3],
    /// Hold-point world position — where a grabbed part floats to.
    pub hold_target: [f32; 3],
    /// Target orientation for a held part (the orbit-center look basis, plus any
    /// rotate-gesture adjustment), so the held part doesn't tumble.
    pub hold_rotation: [f32; 4],
    /// The client's intent to be holding a part.
    pub grab: bool,
    /// One-shot intent to attach (joint) the held part to whatever it's touching.
    pub attach: bool,
    /// One-shot intent to delete a joint inside the delete zone (the empty-handed
    /// modifier-click gesture). The server finds the joint within `DELETE_RADIUS`
    /// of `hold_target` in the player's room and despawns it — mirroring `attach`.
    pub delete: bool,
    /// The lobby room code the client is in (the 6-char matchmaker code as raw
    /// bytes, zero-padded; all-zero = no code / default room). Constant for the
    /// session — carried on the already-reliable input channel rather than a
    /// separate connect message, so the server learns each client's room from its
    /// first input and scopes that client's world to it.
    pub room: [u8; 6],
    /// A stable per-player id the client persists in `localStorage` and re-sends on
    /// every connect (constant for the session, like `room`). After an iOS tab-
    /// suspension the page must reload — the wasm loop can't be revived in place — so
    /// the server remembers each player's last position keyed by this id and restores
    /// it when the same id reconnects within a grace window (server-authoritative
    /// session resume). An app-level token, NOT the netcode `client_id`, so a quick
    /// reconnect isn't rejected as a duplicate connection. `0` = no resume (native).
    pub resume_id: u64,
}

// Focus range / look-angle and the held-part spring stiffnesses are defined once
// in `part.rs` (the single-player gameplay tunables) and reused here so the
// multiplayer selection/hold matches single-player exactly.
use crate::part::{
    MAX_INTERACT_ANGLE, MAX_INTERACT_DISTANCE, ORIENTING_STIFFNESS, POSITIONING_STIFFNESS,
};

/// The part the player is most directly looking at (smallest look-angle within
/// range) — the same focus rule as single-player. `look` is the grab ray
/// direction (hold_target − grab_origin). `parts` yields `(entity,
/// world_position)`.
pub fn focused_part(
    origin: Vec3,
    look: Vec3,
    parts: impl Iterator<Item = (Entity, Vec3)>,
) -> Option<Entity> {
    let mut best = None;
    let mut smallest_angle = MAX_INTERACT_ANGLE;
    for (entity, pos) in parts {
        let between = pos - origin;
        if between.length_squared() < MAX_INTERACT_DISTANCE * MAX_INTERACT_DISTANCE {
            let angle = look.angle_between(between);
            if angle < smallest_angle {
                smallest_angle = angle;
                best = Some(entity);
            }
        }
    }
    best
}

/// Hold targets farther than this from the held part are treated as stale and
/// ignored by [`apply_hold_spring`] (see the guard there). Comfortably above any
/// real hold distance (`MAX_INTERACT_DISTANCE` = 7.5 plus the hold-point offset),
/// comfortably below the km-scale jump of an origin rebase.
pub const STALE_HOLD_DISTANCE: f32 = 50.0;

/// Critically-damped positioning acceleration that floats a held part to the
/// hold point (matches `position_held_part`'s oscillator). The caller subtracts
/// gravity to cancel the part's weight.
pub fn hold_acceleration(displacement: Vec3, velocity: Vec3) -> Vec3 {
    let damping = 2.0 * POSITIONING_STIFFNESS.sqrt();
    displacement * POSITIONING_STIFFNESS - velocity * damping
}

/// Critically-damped angular acceleration that drives a held part toward its
/// target orientation (matches `orient_held_part`'s oscillator). `rotation_vector`
/// is the axis-angle error (axis · angle) between the target and current rotation.
pub fn orient_acceleration(rotation_vector: Vec3, angular_velocity: Vec3) -> Vec3 {
    let damping = 2.0 * ORIENTING_STIFFNESS.sqrt();
    rotation_vector * ORIENTING_STIFFNESS - angular_velocity * damping
}

/// Apply the held-part spring for one fixed tick through `forces`: float the part
/// toward `hold_target` (critically-damped anti-gravity, cancelling its weight) and
/// orient it toward `hold_rotation` (critically-damped; the unset all-zero seed quat
/// is skipped). Shared by the client's predicted hold (`predict_hold`) and the
/// server's authoritative hold (`server_hold`) so both ends simulate an identical
/// spring and diverge only by round-trip. `position`/`rotation` are the part's current
/// Avian pose read by the caller — NOT `Transform`, which lags within the fixed
/// schedule when `lightyear_avian` owns the Position→Transform sync. Mirrors
/// single-player's `position_held_part`/`orient_held_part` (the same critically-damped
/// math via `hold_acceleration`/`orient_acceleration`); the server can't run those
/// directly because it has no camera-rig `HoldPoint` entity (its target arrives over
/// the wire as a raw position), hence this entity-free formulation.
pub fn apply_hold_spring(
    forces: &mut ForcesItem,
    position: Vec3,
    rotation: Quat,
    hold_target: Vec3,
    hold_rotation: Quat,
    gravity: Vec3,
) {
    // Position: float to the hold point, cancelling the part's weight.
    let displacement = hold_target - position;
    // Stale-target guard: a real hold target is never more than a few meters from
    // the part (`MAX_INTERACT_DISTANCE` bounds the grab). A huge displacement means
    // the target was computed in a different coordinate frame — after an origin
    // rebase (`NetRoomFrame`), the holder's forwarded `hold_target` (and the
    // replicated `NetHold` observers spring toward) stays in the pre-rebase frame
    // for ~1 round trip. Springing a critically-damped oscillator across a km-scale
    // "error" would yeet the part; skipping leaves it in free-fall for a few ticks,
    // which the spring recovers from imperceptibly.
    if displacement.length_squared() > STALE_HOLD_DISTANCE * STALE_HOLD_DISTANCE {
        return;
    }
    let lin_vel = forces.linear_velocity();
    forces.apply_linear_acceleration(hold_acceleration(displacement, lin_vel) - gravity);
    // Orientation: drive toward the target (seeded at pickup + rotate gesture). Skip
    // the unset seed (the all-zero default quat is never a real rotation).
    if hold_rotation.length_squared() > 0.5 {
        let error = (hold_rotation * rotation.conjugate()).to_rotation_vector();
        let ang_vel = forces.angular_velocity();
        forces.apply_angular_acceleration(orient_acceleration(error, ang_vel));
    }
}

